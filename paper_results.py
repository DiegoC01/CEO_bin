def optimum(tag):
    info = INSTANCE_INFO.get(tag.lower())
    return info[3] if info else None


def rpd(value, opt):
    """Relative Percentage Deviation = 100 (valor - optimo) / optimo."""
    if opt in (None, 0) or value is None:
        return None
    return 100.0 * (value - opt) / float(opt)


